package com.clauderemote.session.service

import com.clauderemote.model.ClaudeAccount
import com.clauderemote.model.ClaudeMode
import com.clauderemote.model.ClaudeModel
import com.clauderemote.session.ClaudeConfig

/**
 * `~/.claude-remote/bin/cr-session` (Jarvis F0c, §15.2–15.3): open, facts, close, restore, closed, version — the
 * app's own server steps for a caller that is not the app (Jarvis, a person at a shell). Pure: the script is
 * COMPOSED from the bodies the app itself sends ([ClaudeConfig.detachedCreateBody], [ManifestCommands.tombstoneBody],
 * [ManifestCommands.clearTombstoneBody], [ManifestCommands.closeRecordBody], [ManifestCommands.openedMarkerBody],
 * [CloseFactsCommands.closeFactsBody], [SessionRestore.restoreBody]), so the two cannot drift apart; the tests check
 * the script holds each body byte for byte.
 *
 * Invariants (§15.15): open and restore never run `kill-session` (a taken name is EXISTS); a close writes the durable
 * tombstone, then the record, then kills; nothing here pushes the manifest (drift adopts and drops within 60 s). The
 * script refuses to close the name in `~/.claude-remote/jarvis/self` and anything outside `claude-server-*`, and
 * `~/.claude-remote/jarvis/off` stops open, close and restore.
 *
 * The app does not call it (yet): a broken file on a server must never break closing tabs. It installs it in
 * [DefaultServerBootstrap] ([INSTALL_COMMAND]): no unit, no daemon-reload, just a file.
 */
internal object SessionOpsScript {

    const val VERSION = 1
    const val PATH = "~/.claude-remote/bin/cr-session"
    /** How old a `facts` token `close` still accepts. */
    const val TOKEN_MAX_AGE_S = 120
    const val MARKER = "claude-remote-session-ops-v"

    private fun sh(s: String) = s.replace('§', '$')

    /** `case` arms model name → `B` (binary) and `MA` (model args), from [ClaudeConfig]'s own pieces. */
    private fun modelArms(): String = ClaudeModel.entries.joinToString(" ") { m ->
        val ma = ClaudeConfig.modelArgs(m).joinToString(" ").let { if (it.isEmpty()) "" else " $it" }
        "${m.name}) B=${ClaudeConfig.claudeBinary(m)}; MA='$ma' ;;"
    }

    /** `case` arms mode name → `PA` (permission args). */
    private fun modeArms(): String = ClaudeMode.entries.joinToString(" ") { m ->
        "${m.name}) PA=' ${ClaudeConfig.modeArgs(m).joinToString(" ")}' ;;"
    }

    /**
     * `cr_cmd FOLDER MODE MODEL SESSION_ID RESUME(1|0) ACCOUNT` prints the pane's launch command, the string
     * [ClaudeConfig.buildLaunchCommand] builds for the same inputs (a test compares them over every mode and model):
     * `cd` with `~` / `~/` left bare and the rest single-quoted, the account's `CLAUDE_CONFIG_DIR=` prefix (none for
     * `default` or empty), then the claude arguments.
     */
    internal val CLAUDE_CMD_SH: String = sh(
        """
        cr_q() { printf "'%s'" "§(printf '%s' "§1" | sed "s/'/'\\\\''/g")"; }
        cr_path() { case "§1" in '~') printf '%s' '~' ;; '~/'*) printf '%s' '~/'; cr_q "§{1#\~/}" ;; *) cr_q "§1" ;; esac; }
        cr_cmd() {
          case "§3" in @@MODELS@@ *) return 1 ;; esac
          case "§2" in @@MODES@@ *) return 1 ;; esac
          SA=""; if [ -n "§4" ]; then if [ "§5" = 1 ]; then SA=" --resume §4"; else SA=" --session-id §4"; fi; fi
          PFX=""; case "§6" in ''|@@DEFAULT@@) ;; *) PFX="CLAUDE_CONFIG_DIR=§(cr_path "@@ROOT@@/§6") " ;; esac
          printf 'cd %s && %s%s%s%s%s' "§(cr_path "§1")" "§PFX" "§B" "§MA" "§PA" "§SA"
        }
        """.trimIndent(),
    ).replace("@@MODELS@@", modelArms()).replace("@@MODES@@", modeArms())
        .replace("@@DEFAULT@@", ClaudeAccount.DEFAULT_SLUG).replace("@@ROOT@@", ClaudeAccount.ACCOUNTS_ROOT)

    val SCRIPT: String by lazy {
        TEMPLATE
            .replace("@@JSON@@", ManifestCommands.JSON_SH)
            .replace("@@CMD@@", CLAUDE_CMD_SH)
            .replace("@@MANIFEST@@", ManifestCommands.MANIFEST_SH)
            .replace("@@TOMBSTONE@@", ManifestCommands.tombstoneBody(marker = true))
            .replace("@@CLEAR@@", ManifestCommands.clearTombstoneBody())
            .replace("@@RECORD@@", ManifestCommands.closeRecordBody())
            .replace("@@MARKER@@", ManifestCommands.openedMarkerBody())
            .replace("@@FACTS@@", CloseFactsCommands.closeFactsBody())
            .replace("@@RESTORE@@", SessionRestore.restoreBody())
            .replace("@@SPAWN@@", ClaudeConfig.detachedCreateBody())
            .replace("@@WAIT@@", SessionRestore.WAIT_REGISTRY)
            .replace("@@MAXAGE@@", TOKEN_MAX_AGE_S.toString())
    }

    private val TEMPLATE = sh(
        """
        #!/usr/bin/env bash
        # $MARKER$VERSION
        # marker-compat (keep inside `head -c 300`): $MARKER$VERSION
        # cr-session: open | facts | close | restore | closed | version. Generated by the claude-remote app from the
        # builders it sends itself (SessionOpsScript); the app rewrites a damaged copy of this version. Do not edit.
        set -u
        VERSION=$VERSION
        D="§HOME/.claude-remote"
        @@JSON@@
        @@CMD@@
        @@MANIFEST@@
        usage() {
          cat <<'CR_USAGE'
        usage: cr-session version
               cr-session open --name N --folder F [--account SLUG|default] [--model M] [--mode yolo|normal|auto|accept|plan]
                               [--session-id UUID | --resume UUID] [--by WHO] [--task T] [--wait S]
               cr-session facts N [--self MARKER]
               cr-session close N --token T [--reason R] [--by WHO]
               cr-session restore <tmuxName|at> [--name N] [--session-id UUID | --fresh] [--wait S] [--by WHO]
               cr-session closed [COUNT]
        CR_USAGE
        }
        log() { printf '[%s] %s\n' "§(date -u +%FT%TZ)" "§*" >> "§D/jarvis-ops.log" 2>/dev/null; }
        refuse_off() { [ -e "§D/jarvis/off" ] && { echo REFUSED_OFF; exit 1; }; return 0; }
        need() { [ "§1" -ge 2 ] || { echo "INVALID missing value for §2"; exit 2; }; }
        # a new name: ours, and one drift's word-split listing reads back whole
        valid_new_name() { case "§1" in claude-server-*) ;; *) return 1 ;; esac; case "§1" in *[./:]*|*[[:space:]]*) return 1 ;; esac; return 0; }
        has() { timeout 3 tmux has-session -t "=§1" 2>/dev/null; }
        cr_tombstone() ( N=§1
        @@TOMBSTONE@@
        )
        cr_clear() ( N=§1
        @@CLEAR@@
        )
        cr_record() ( N=§1; BY=§2; DUR=1; REASON=§3
        @@RECORD@@
        )
        cr_marker() ( N=§1; BY=§2; F=§3; A=§4; S=§5; TASK=§6
        @@MARKER@@
        )
        cr_facts() ( N=§1; SELF=§2
        @@FACTS@@
        )
        cr_restore() ( N=§1; S=§2; S2=§3; F=§4; A=§5; CMD=§6; CMD2=§7; FRESH=§8; AT_EPOCH=§9; WAIT=§{10}
        @@RESTORE@@
        )
        # not a subshell: the caller reads CR_SG (the socket guard's verdict) afterwards
        cr_spawn() { NAME=§1; CMD=§2
        @@SPAWN@@
        }
        cr_wait() { N=§1; WAIT=§2
        @@WAIT@@
        }
        upper() { printf '%s' "§1" | tr 'a-z-' 'A-Z_'; }
        mode_of() {
          case "§1" in
            yolo|YOLO) echo YOLO ;; normal|NORMAL|default) echo NORMAL ;; auto|AUTO) echo AUTO ;;
            accept|acceptEdits|auto-accept|AUTO_ACCEPT) echo AUTO_ACCEPT ;; plan|PLAN) echo PLAN ;; *) echo "§1" ;;
          esac
        }

        cmd_open() {
          NAME=""; FOLDER=""; ACCT=default; MODEL=DEFAULT; MODE=YOLO; SID=""; RESUME=0; BY=jarvis; TASK=""; WAIT=15
          while [ §# -gt 0 ]; do
            case "§1" in
              --name) need §# "§1"; NAME=§2 ;;
              --folder) need §# "§1"; FOLDER=§2 ;;
              --account) need §# "§1"; ACCT=§2 ;;
              --model) need §# "§1"; MODEL=§(upper "§2") ;;
              --mode) need §# "§1"; MODE=§(mode_of "§2") ;;
              --session-id) need §# "§1"; SID=§2; RESUME=0 ;;
              --resume) need §# "§1"; SID=§2; RESUME=1 ;;
              --by) need §# "§1"; BY=§2 ;;
              --task) need §# "§1"; TASK=§2 ;;
              --wait) need §# "§1"; WAIT=§2 ;;
              *) echo "INVALID unknown option §1"; exit 2 ;;
            esac
            shift 2
          done
          valid_new_name "§NAME" || { echo "INVALID name"; exit 2; }
          case "§FOLDER" in
            '') echo "INVALID folder"; exit 2 ;;
            '~') FD=§HOME ;; '~/'*) FD="§HOME/§{FOLDER#\~/}" ;; /*) FD=§FOLDER ;; *) FD="§HOME/§FOLDER" ;;
          esac
          [ -d "§FD" ] || { echo "INVALID folder §FD"; exit 2; }
          case "§ACCT" in
            default) AS="" ;;
            ''|*/*|.*) echo "INVALID account"; exit 2 ;;
            *) [ -d "§D/accounts/§ACCT" ] || { echo "INVALID account §ACCT"; exit 2; }; AS=§ACCT ;;
          esac
          case "§SID" in '') SID=§(cat /proc/sys/kernel/random/uuid 2>/dev/null) ;; *[!0-9a-f-]*) echo "INVALID session id"; exit 2 ;; esac
          case "§WAIT" in ''|*[!0-9]*) WAIT=15 ;; esac
          refuse_off
          has "§NAME" && { echo EXISTS; exit 1; }
          # a manifest entry of the name that is not tombstoned: drift's self-heal is about to start it (§15.15)
          if in_manifest "§NAME" && ! tombstoned "§NAME"; then echo PENDING_SELF_HEAL; exit 1; fi
          CMD=§(cr_cmd "§FD" "§MODE" "§MODEL" "§SID" "§RESUME" "§AS") || { echo "INVALID model or mode"; exit 2; }
          # the tombstone goes BEFORE the start: drift would subtract the name and peers forget the tab (§15.7)
          cr_clear "§NAME" >/dev/null 2>&1
          cr_spawn "§NAME" "§CMD"; RC=§?
          if [ §RC -ne 0 ]; then
            if [ "§{CR_SG:-0}" -ne 0 ] && [ "§{CR_SG:-0}" -ne 3 ]; then echo "REFUSED_GUARD §CR_SG"; exit 1; fi
            has "§NAME" && { echo EXISTS; exit 1; }
            echo "FAILED rc=§RC"; exit 1
          fi
          cr_marker "§NAME" "§BY" "§FD" "§AS" "§SID" "§TASK"
          cr_wait "§NAME" "§WAIT"
          log "open §NAME by=§BY folder=§FD account=§ACCT sid=§SID resume=§RESUME → §RSTATE"
          case "§RSTATE" in
            ok) echo "OPENED {\"name\":§(js "§NAME"),\"pane\":§(jn "§RPANE"),\"pid\":§{RPID:-null},\"sessionId\":§(jn "§RSID")}" ;;
            login) echo OPENED_LOGIN_REQUIRED ;;
            *) echo OPENED_NO_REGISTRY ;;
          esac
        }

        cmd_facts() {
          [ §# -ge 1 ] && [ -n "§1" ] || { echo "INVALID name"; exit 2; }
          N=§1; SELFM=""
          [ "§{2:-}" = --self ] && SELFM=§{3:-}
          cr_facts "§N" "§SELFM"
        }

        cmd_close() {
          [ §# -ge 1 ] || { echo "INVALID name"; exit 2; }
          N=§1; shift; TOKEN=""; REASON=""; BY=jarvis
          while [ §# -gt 0 ]; do
            case "§1" in
              --token) need §# "§1"; TOKEN=§2 ;;
              --reason) need §# "§1"; REASON=§2 ;;
              --by) need §# "§1"; BY=§2 ;;
              *) echo "INVALID unknown option §1"; exit 2 ;;
            esac
            shift 2
          done
          case "§N" in claude-server-*) ;; *) echo REFUSED_NAME; exit 1 ;; esac
          case "§N" in */*|*'
        '*) echo REFUSED_NAME; exit 1 ;; esac
          ME=§(head -n 1 "§D/jarvis/self" 2>/dev/null)
          [ -n "§ME" ] && [ "§ME" = "§N" ] && { echo REFUSED_SELF; exit 1; }
          refuse_off
          [ -n "§TOKEN" ] || { echo "INVALID missing --token (from cr-session facts)"; exit 2; }
          TE=§{TOKEN%%.*}; TH=§{TOKEN#*.}; NOW=§(date +%s)
          case "§TE" in ''|*[!0-9]*) echo REFUSED_STALE; exit 1 ;; esac
          if [ §((NOW - TE)) -gt @@MAXAGE@@ ] || [ §((TE - NOW)) -gt 5 ]; then echo REFUSED_STALE; exit 1; fi
          CUR=§(cr_facts "§N" "" | sed -n 's/^TOKEN //p')
          [ -n "§CUR" ] && [ "§{CUR#*.}" = "§TH" ] || { echo REFUSED_STALE; exit 1; }
          # the app's order: tombstone, record (the pane still lives), kill (§15.15)
          cr_tombstone "§N" >/dev/null 2>&1
          cr_record "§N" "§BY" "§REASON"
          timeout 5 tmux kill-session -t "=§N" 2>/dev/null; KR=§?
          rm -f "§{D:?}/opened.d/§{N:?}"
          log "close §N by=§BY kill=§KR reason=§REASON"
          echo CLOSED
        }

        cmd_restore() {
          [ §# -ge 1 ] && [ -n "§1" ] || { echo "INVALID record (tmuxName or at)"; exit 2; }
          KEY=§1; shift; NEW=""; SIDO=""; FRESH=0; WAIT=15; BY=jarvis
          while [ §# -gt 0 ]; do
            case "§1" in
              --name) need §# "§1"; NEW=§2; shift 2 ;;
              --session-id) need §# "§1"; SIDO=§2; shift 2 ;;
              --fresh) FRESH=1; shift ;;
              --wait) need §# "§1"; WAIT=§2; shift 2 ;;
              --by) need §# "§1"; BY=§2; shift 2 ;;
              *) echo "INVALID unknown option §1"; exit 2 ;;
            esac
          done
          case "§WAIT" in ''|*[!0-9]*) WAIT=15 ;; esac
          refuse_off
          command -v jq >/dev/null 2>&1 || { echo "FAILED jq missing"; exit 1; }
          REC=§(tail -n 500 "§D/closed.jsonl" 2>/dev/null | jq -c -R --arg k "§KEY" 'fromjson? | select(.tmuxName == §k or .at == §k)' 2>/dev/null | tail -n 1)
          [ -n "§REC" ] || { echo NOT_FOUND; exit 1; }
          f() { printf '%s' "§REC" | jq -r "§1 // empty" 2>/dev/null; }
          N=§(f .tmuxName); S=§(f .sessionId); S2=§(f .launchSessionId); F=§(f '.cwd // .folder'); A=§(f .account)
          MODEL=§(f .model); MODE=§(f .mode); AT=§(f .at)
          [ -n "§MODEL" ] || MODEL=DEFAULT
          if [ -z "§MODE" ]; then
            if printf '%s' "§REC" | jq -e '(.flags // []) | index("--dangerously-skip-permissions")' >/dev/null 2>&1; then MODE=YOLO; else MODE=NORMAL; fi
          fi
          [ -n "§S" ] || S=§S2
          [ "§S2" = "§S" ] && S2=""
          if [ -n "§NEW" ]; then valid_new_name "§NEW" || { echo "INVALID name"; exit 2; }; N=§NEW; fi
          [ -n "§SIDO" ] && { S=§SIDO; S2=""; }
          [ "§FRESH" = 1 ] && { S=§(cat /proc/sys/kernel/random/uuid 2>/dev/null); S2=""; }
          [ -n "§F" ] || { echo "FAILED record has no folder"; exit 1; }
          if [ "§FRESH" = 1 ]; then R=0; else R=1; fi
          CMD=§(cr_cmd "§F" "§MODE" "§MODEL" "§S" "§R" "§A") || { echo "FAILED record model/mode"; exit 1; }
          CMD2=""; [ -n "§S2" ] && CMD2=§(cr_cmd "§F" "§MODE" "§MODEL" "§S2" 1 "§A")
          AE=§(date -d "§AT" +%s 2>/dev/null)
          OUT=§(cr_restore "§N" "§S" "§S2" "§F" "§A" "§CMD" "§CMD2" "§FRESH" "§AE" "§WAIT")
          log "restore §KEY as §N by=§BY → §OUT"
          printf '%s\n' "§OUT"
          case "§OUT" in *" RESTORED"*|*" OPENED_LOGIN_REQUIRED"*) return 0 ;; *) exit 1 ;; esac
        }

        cmd_closed() {
          L=§{1:-10}; case "§L" in ''|*[!0-9]*) L=10 ;; esac
          [ -f "§D/closed.jsonl" ] && tail -n "§L" "§D/closed.jsonl"
          return 0
        }

        case "§{1:-}" in
          version|--version) echo "cr-session v§VERSION" ;;
          open) shift; cmd_open "§@" ;;
          facts) shift; cmd_facts "§@" ;;
          close) shift; cmd_close "§@" ;;
          restore) shift; cmd_restore "§@" ;;
          closed) shift; cmd_closed "§@" ;;
          *) usage; exit 2 ;;
        esac
        """.trimIndent(),
    )

    /** Size and SHA-256 of the script as [INSTALL_COMMAND] writes it (the script and the heredoc's final newline). */
    private val SCRIPT_BYTES: ByteArray by lazy { (SCRIPT + "\n").encodeToByteArray() }
    internal val SCRIPT_SHA256: String by lazy {
        java.security.MessageDigest.getInstance("SHA-256").digest(SCRIPT_BYTES).joinToString("") { "%02x".format(it) }
    }

    /**
     * Writes [PATH] (temp + chmod 755 + mv), the pattern of `hook-ev.sh` (`HookCommands`): a file of a NEWER version
     * is left alone; one of this version only when it is intact (size and, where `sha256sum` exists, SHA-256 match),
     * so a damaged file with a valid header is rewritten instead of trusted forever. Prints `SESSIONOPS_PRESENT`,
     * `SESSIONOPS_INSTALLED` or `SESSIONOPS_FAILED`. Never exits the shell it runs in.
     */
    val INSTALL_COMMAND: String by lazy {
        sh(
            "F=\"§HOME/.claude-remote/bin/cr-session\"; mkdir -p \"§HOME/.claude-remote/bin\"; " +
                "CUR=§(head -c 300 \"§F\" 2>/dev/null | grep -o '$MARKER[0-9][0-9]*' | sed 's/.*-v//' | sort -n | tail -n1); " +
                "KEEP=0; if [ -n \"§CUR\" ]; then " +
                "if [ \"§CUR\" -gt $VERSION ]; then KEEP=1; " +
                "elif [ \"§CUR\" -eq $VERSION ]; then " +
                "SZ=§(wc -c < \"§F\" 2>/dev/null | tr -d ' '); HS=§(sha256sum < \"§F\" 2>/dev/null | cut -d' ' -f1); " +
                "[ \"§SZ\" = ${SCRIPT_BYTES.size} ] && { [ -z \"§HS\" ] || [ \"§HS\" = $SCRIPT_SHA256 ]; } && KEEP=1; fi; fi; " +
                "if [ \"§KEEP\" = 1 ]; then echo SESSIONOPS_PRESENT; else " +
                "T=\"§F.tmp.§§\"; cat > \"§T\" <<'CRSO_SH'\n",
        ) + SCRIPT + "\nCRSO_SH\n" +
            sh("if chmod 755 \"§T\" && mv -f \"§T\" \"§F\"; then echo SESSIONOPS_INSTALLED; else echo SESSIONOPS_FAILED; fi; fi")
    }
}
