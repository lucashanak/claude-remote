            SessionPersistenceService.INSTALL_RESTORE_EXEC,
            timeoutMs = 60_000,
            stdin = SessionPersistenceService.installRestoreStdin(),
        )
        assertEquals(0, result.exit, "install command failed:\n${result.out}")
        return result.out
    }

