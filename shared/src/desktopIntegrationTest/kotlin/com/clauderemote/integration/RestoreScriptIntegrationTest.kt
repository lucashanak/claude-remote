    /**
     * restore.sh writes NOTHING to stdout (`exec >> restore.log`), so its log is
     * the only diagnostic — and these four lines are its silent-failure modes.
     */
    private fun assertRestoreLogIsClean(log: String) {
        for (bad in listOf(
            "skipping restore",       // no tmux server: exits 0 doing nothing
            "FAILED to restore",      // tmux new-session rejected the request
            "invalid session",        // manifest entry tmux would not accept
            "Cannot index object",    // jq handed an object where it wants an array
            "not in PATH",            // tmux/claude missing
            "nothing to restore",     // manifest never found
        )) {
            assertFalse(log.contains(bad), "restore.log contains \"$bad\":\n$log")
        }
    }

