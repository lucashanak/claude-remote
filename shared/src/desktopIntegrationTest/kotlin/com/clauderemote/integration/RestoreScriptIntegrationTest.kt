    /** Produce the manifest with the APP's serializer — never hand-written JSON. */
    private fun serializeWithApp(vararg sessions: PersistedSession): String {
        val storage = SessionStorage(InMemoryKeyValueStore())
        sessions.forEach { storage.upsert(it) }
        // A session on ANOTHER server must not leak into this server's manifest.
        storage.upsert(
            sessions.first().copy(id = "other", serverId = "other-server", tmuxSessionName = "claude-server-other--x"),
        )
        val json = storage.serializeForServer(SERVER_ID)
        assertFalse(json.contains("claude-server-other--x"), "serializeForServer must filter by serverId")
        return json
    }

